"""Deterministic, reviewable SQL text dumps of a StrataLeaf database.

The fixture is committed as SQL rather than as an opaque binary so that a
maintainer can diff column values and encoding changes during review.  The dump
is produced from a database that was built through the public API; loading the
dump back through SQLite reproduces the same logical rows (rowid order and
therefore insert order are preserved).
"""
import sqlite3
from pathlib import Path


def quote_identifier(value):
    return '"' + value.replace('"', '""') + '"'


def literal(value):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if value != value or value in (float("inf"), float("-inf")):
            raise ValueError("non-finite float cannot be stored in a format-1 sample")
        return repr(value)
    if isinstance(value, str):
        return "'" + value.replace("'", "''") + "'"
    if isinstance(value, bytes):
        return "X'" + value.hex() + "'"
    raise TypeError("unsupported SQLite value type: " + type(value).__name__)


def dump_database(database, destination, note=None):
    """Write schema and data of *database* to *destination* as SQL text."""
    database, destination = Path(database), Path(destination)
    connection = sqlite3.connect(database.resolve().as_uri() + "?mode=ro", uri=True)
    try:
        objects = connection.execute(
            "SELECT type,name,sql FROM sqlite_master "
            "WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' "
            "ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END, name"
        ).fetchall()
        tables = [name for kind, name, _ in objects if kind == "table"]
        lines = []
        if note:
            lines.extend("-- " + line for line in note.splitlines())
        lines.append("-- Generated by compat.dump from a database built through the public API.")
        lines.append("PRAGMA foreign_keys=OFF;")
        lines.append("BEGIN TRANSACTION;")
        for kind, name, sql in objects:
            lines.append(sql.rstrip(";") + ";")
        for table in tables:
            columns = [row[1] for row in connection.execute("PRAGMA table_info(" + quote_identifier(table) + ")")]
            heading = ", ".join(quote_identifier(column) for column in columns)
            try:
                rows = connection.execute(
                    "SELECT * FROM " + quote_identifier(table) + " ORDER BY rowid"
                ).fetchall()
            except sqlite3.OperationalError:
                rows = connection.execute("SELECT * FROM " + quote_identifier(table)).fetchall()
            for row in rows:
                values = ", ".join(literal(value) for value in row)
                lines.append("INSERT INTO " + quote_identifier(table)
                             + " (" + heading + ") VALUES (" + values + ");")
        lines.append("COMMIT;")
        destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
    finally:
        connection.close()
    return destination


def load_database(source, destination):
    """Materialize a SQL dump into a fresh database file and check integrity."""
    source, destination = Path(source), Path(destination)
    if destination.exists():
        destination.unlink()
    connection = sqlite3.connect(destination)
    try:
        connection.executescript(source.read_text(encoding="utf-8"))
        connection.commit()
        connection.execute("PRAGMA foreign_keys=ON")
        integrity = connection.execute("PRAGMA integrity_check").fetchone()[0]
        references = connection.execute("PRAGMA foreign_key_check").fetchall()
        if integrity != "ok" or references:
            raise ValueError("loaded sample is not intact: " + integrity + " " + repr(references))
    finally:
        connection.close()
    return destination
