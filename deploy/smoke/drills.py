_READER_SCRIPT = r"""
import sqlite3, sys, time
path, seconds = sys.argv[1], float(sys.argv[2])
# Hold a read transaction over the real storage table. BEGIN (deferred) plus
# the first read pins the snapshot; the WAL cannot be checkpointed past it.
connection = sqlite3.connect(path, isolation_level=None)
connection.execute("BEGIN")
connection.execute("SELECT COUNT(*) FROM versions").fetchone()
print("reader-ready", flush=True)
time.sleep(seconds)
connection.execute("ROLLBACK")
connection.close()
"""

_TORN_SCRIPT = r"""
import json, os, sqlite3, sys, threading
path, revision = sys.argv[1], int(sys.argv[2])
connection = sqlite3.connect(path, isolation_level=None)
connection.execute("PRAGMA journal_mode=WAL")
connection.execute("PRAGMA synchronous=FULL")
# Force the open transaction to spill into -wal before the kill, so this drill
# proves rollback of *durable* uncommitted frames rather than an in-memory
# transaction that never reached disk.
connection.execute("PRAGMA cache_size=1")
connection.execute("BEGIN IMMEDIATE")
body = json.dumps({"worker": "phantom", "seq": -1}, sort_keys=True, separators=(",", ":"))
connection.execute("INSERT INTO versions VALUES ('events','phantom',?,?,NULL)", (revision, body))
connection.execute("INSERT INTO index_values VALUES ('events','by_seq','n:-1','phantom')")
connection.execute("INSERT INTO commits VALUES (?,?,NULL,NULL)",
                   (revision, json.dumps({"revision": revision, "operations": [
                       {"collection": "events", "key": "phantom", "document": {"worker": "phantom", "seq": -1},
                        "expected": None, "expires_at": None}]})))
connection.execute("UPDATE meta SET value=? WHERE key='head'", (str(revision),))
for index in range(48):
    connection.execute("INSERT INTO versions VALUES ('events', ?, ?, ?, NULL)",
                       ("filler_%02d" % index, revision + 1 + index,
                        json.dumps({"pad": "x" * 8000})))
wal_after = os.path.getsize(path + "-wal")
print(json.dumps({"event": "torn-ready", "wal_bytes": wal_after,
                  "head_in_txn": revision}), flush=True)
# Block inside the open transaction; the parent SIGKILLs us here.
threading.Event().wait()
"""

_SPACE_SCRIPT = r"""import json, os, resource, sqlite3, sys
path, limit = sys.argv[1], int(sys.argv[2])
resource.setrlimit(resource.RLIMIT_FSIZE, (limit, limit))
connection = sqlite3.connect(path, timeout=1.0, isolation_level=None)
connection.execute("PRAGMA journal_mode=WAL")
print(json.dumps({"event": "start", "head": connection.execute("SELECT value FROM meta WHERE key='head'").fetchone()[0]}))
for index in range(5000):
    try:
        connection.execute("INSERT INTO versions VALUES ('segments', ?, ?, ?, NULL)",
                           ("fill_%05d" % index, 1000000 + index, json.dumps({"pad": "x" * 2048})))
    except Exception as exc:
        print(json.dumps({"event": "write-failed", "index": index,
                          "error": str(exc), "type": type(exc).__name__}))
        break
else:
    print(json.dumps({"event": "no-failure"}))
try:
    print(json.dumps({"event": "post-failure-quick-check",
                      "result": connection.execute("PRAGMA quick_check").fetchone()[0]}))
except Exception as exc:
    print(json.dumps({"event": "quick-check-error", "error": str(exc)}))
try:
    connection.close()
except Exception as exc:
    print(json.dumps({"event": "close-error", "error": str(exc)}))
"""


def _quick_check(db: Path) -> str:
    connection = sqlite3_connect_readonly(db)
    try:
        return connection.execute("PRAGMA quick_check").fetchone()[0]
    finally:
        connection.close()


def _recovered_evidence(config: dict) -> dict:
    """Post-recovery documents, retained log range, index, and fingerprint.

    This is the operator-visible answer to "what actually came back": the
    documents a fresh reader sees at head, the contiguous commit log still
    retained, the materialised index rows, and a content fingerprint.
    """
    paths = ops.config_paths(config)
    connection = sqlite3_connect_readonly(paths["db"])
    connection.row_factory = ops.sqlite3.Row
    try:
        meta = dict(connection.execute("SELECT key,value FROM meta"))
        head, floor = int(meta["head"]), int(meta["floor"])
        documents = [
            {"key": row["key"], "revision": row["rev"], "document": json.loads(row["body"])}
            for row in ops._visible_rows(connection, "events", head)
        ]
        log = [row[0] for row in connection.execute(
            "SELECT rev FROM commits WHERE rev>? ORDER BY rev", (floor,))]
        receipts = connection.execute("SELECT COUNT(*) FROM receipts").fetchone()[0]
        index_defs = [dict(row) for row in connection.execute("SELECT * FROM index_defs")]
        index_rows = connection.execute(
            "SELECT COUNT(*) FROM index_values WHERE collection='events'").fetchone()[0]
        expected_index = 0
        for definition in connection.execute("SELECT * FROM index_defs WHERE collection='events'"):
            for row in ops._visible_rows(connection, "events", head):
                if ops._scalar_token(ops._field(json.loads(row["body"]), definition["field"])) is not None:
                    expected_index += 1
        return {
            "head": head, "floor": floor,
            "log_first": log[0] if log else None, "log_last": log[-1] if log else None,
            "log_contiguous": log == list(range(floor + 1, head + 1)),
            "receipts": receipts,
            "documents": documents,
            "index_defs": index_defs,
            "index_rows": index_rows,
            "index_expected_rows": expected_index,
            "index_matches_documents": index_rows == expected_index,
            "fingerprint": ops._fingerprint(connection, head),
        }
    finally:
        connection.close()


def sqlite3_connect_readonly(db: Path):
    import sqlite3
    return sqlite3.connect(db.resolve().as_uri() + "?mode=ro", uri=True)


def _visible_keys(db: Path) -> list[str]:
    connection = sqlite3_connect_readonly(db)
    try:
        head = int(dict(connection.execute("SELECT key,value FROM meta"))["head"])
        rows = connection.execute("""SELECT key FROM versions v WHERE rev<=? AND body IS NOT NULL
          AND NOT EXISTS (SELECT 1 FROM versions n WHERE n.collection=v.collection
          AND n.key=v.key AND n.rev>v.rev AND n.rev<=?)""", (head, head))
        return [row[0] for row in rows]
    finally:
        connection.close()


def _fingerprint_at(config: dict, revision: int) -> str:
    """Fingerprint a historical revision using the operator tool's read path."""
    import sqlite3
    paths = ops.config_paths(config)
    connection = sqlite3.connect(paths["db"].resolve().as_uri() + "?mode=ro", uri=True)
    connection.row_factory = sqlite3.Row
    try:
        return ops._fingerprint(connection, revision)["sha256"]
    finally:
        connection.close()


def _probe_status(function, *args, **kwargs) -> dict:
    try:
        report = function(*args, **kwargs)
        return {"status": report["status"], "details": {
            "write_lock": report.get("write_lock"),
            "checkpoint": report.get("checkpoint"),
            "wal": report.get("wal"),
            "reason": report.get("reason"),
        }}
    except ops.GateError as exc:
        return {"status": "unhealthy", "reason": str(exc)}


def _current_user() -> str:
    try:
        import pwd
        return pwd.getpwuid(os.getuid()).pw_name
    except (ImportError, KeyError):
        return f"uid{os.getuid()}"


