"""Reproducible container lifecycle drills for StrataLeaf.

These are *not* a unit-test suite (the project keeps automated tests deferred).
They are executable evidence: a scripted operator runs a real service process
against real persistent directories, then stops it normally or kills it, and
checks what survived.

Design rules
------------
* Every drill gets a fresh workspace with `data/` and `state/` volumes; nothing
  touches a production path.
* Identity is verified rather than assumed: if the running uid is not the
  configured uid, the drill reports `identity_simulated` and preflight proves
  it rejects mismatched identities.
* Chaos is injected with real process signals and real resource limits
  (`RLIMIT_FSIZE` for disk exhaustion), never by editing files behind the
  library's back.
* A drill fails if the *absence* of durable data is mistaken for health: the
  false-health section must demonstrate that process-alive, file-exists,
  open-handle, and no-exception-checkpoint checks all pass while the real
  probe correctly reports the blocking condition.
"""

from __future__ import annotations

import json
import os
import shutil
import signal
import subprocess
import sys
import time
from pathlib import Path

