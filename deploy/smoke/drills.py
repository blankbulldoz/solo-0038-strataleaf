def normal_stop(config: dict, root: Path) -> dict:
    """SIGTERM while serving; assert clean close, checkpoint, and recovery."""
    config_path = _prepare_workspace(root / "normal", config, root / "normal" / "service.conf")
    log = root / "normal" / "supervisor.log"
    process = _run_child(config_path, seconds=60, batch_interval=0.03, log=log)
    try:
        running = root / "normal" / "state" / "running.json"
        if not _wait_for(lambda: running.exists(), timeout=20):
            raise RuntimeError("service never published running state")
        before = _wait_for_commits(running, 5, timeout=20)
        process.send_signal(signal.SIGTERM)
        started = time.monotonic()
        finished = process.wait(timeout=config["STRATALEAF_STOP_TIMEOUT_SECONDS"] + 5)
        elapsed = round(time.monotonic() - started, 3)
    finally:
        process._log_handle.close()
        if process.poll() is None:
            process.kill()
    clean = root / "normal" / "state" / "clean-stop.json"
    marker = json.loads(clean.read_text()) if clean.exists() else None
    paths = ops.config_paths(ops.load_config(config_path))
    after_service = {"wal": paths["wal"].stat().st_size if paths["wal"].exists() else None,
                     "shm": paths["shm"].exists(),
                     "files": {p.name: p.stat().st_size for p in paths["data_dir"].iterdir()}}
    # Normalize the on-disk state: an independent connection that checkpoints
    # and closes last is what removes -wal/-shm. Run the shipped post-stop
    # verification, which is exactly this sequence.
    verify_config = ops.load_config(config_path)
    recovered = ops.verify(verify_config, deep=True, expect_head=marker["head_on_disk"] if marker else None)
    at_rest = {
        "wal_bytes_after_verify": paths["wal"].stat().st_size if paths["wal"].exists() else None,
        "shm_present_after_verify": paths["shm"].exists(),
        "files": {p.name: p.stat().st_size for p in paths["data_dir"].iterdir()},
    }
    checks = {
        "exit_code_zero": finished == ops.EXIT_OK,
        "clean_marker_written": marker is not None,
        "marker_after_close_reports_head": marker is not None and marker["head_on_disk"] == marker["revision_before_close"],
        "checkpoint_completed_before_close": marker is not None and marker["checkpoint"]["complete"],
        "wal_empty_at_rest": after_service["wal"] in (0, None),
        "sigterm_not_sigkill": finished != -signal.SIGKILL,
        "commits_recorded": marker is not None and marker["commits"] > 0,
    }
    checks["recovery_integrity_ok"] = recovered["ok"]
    checks["recovery_fingerprint_matches"] = (
        recovered["fingerprint"]["sha256"] == _fingerprint_at(verify_config, marker["revision_before_close"])
        if marker else False)
    evidence = _recovered_evidence(verify_config)
    checks["log_contiguous_after_recovery"] = evidence["log_contiguous"]
    checks["index_matches_documents_after_recovery"] = evidence["index_matches_documents"]
    checks["all_reported_commits_present"] = (
        marker is not None and evidence["log_last"] == marker["revision_before_close"])
    return {
        "drill": "normal-stop", "ok": all(checks.values()), "checks": checks,
        "exit_code": finished, "stop_seconds": elapsed,
        "commits_before_stop": before["commits"], "clean_stop": marker,
        "files_after_service_exit": after_service, "at_rest_after_verify": at_rest,
        "verification": recovered, "recovered_evidence": evidence,
        "log_events": _jsonl(root / "normal" / "state" / "service.log")[-12:],
        "note": "the -wal/-shm files remain (zero-length WAL) after the service's own "
                "close because the last connection to close decides their removal; "
                "committed data is durable either way, and the post-stop verify reads "
                "the same head with or without them",
    }


def sigkill_stop(config: dict, root: Path) -> dict:
    """SIGKILL while serving; assert WAL recovery, no phantom commits, and sane ordering."""
    config_path = _prepare_workspace(root / "sigkill", config, root / "sigkill" / "service.conf")
    log = root / "sigkill" / "supervisor.log"
    process = _run_child(config_path, seconds=60, batch_interval=0.03, log=log)
    try:
        running = root / "sigkill" / "state" / "running.json"
        if not _wait_for(lambda: running.exists(), timeout=20):
            raise RuntimeError("service never published running state")
        before = _wait_for_commits(running, 5, timeout=20)
        process.send_signal(signal.SIGKILL)
        finished = process.wait(timeout=10)
    finally:
        process._log_handle.close()
    paths = ops.config_paths(ops.load_config(config_path))
    at_crash = {
        "wal_exists": paths["wal"].exists(),
        "shm_exists": paths["shm"].exists(),
        "sizes": {p.name: p.stat().st_size for p in paths["data_dir"].iterdir()},
        "pid_file_state": "running" if (root / "sigkill" / "state" / "running.json").exists() else "missing",
        "clean_marker": (root / "sigkill" / "state" / "clean-stop.json").exists(),
    }
    verify_config = ops.load_config(config_path)
    recovered = ops.verify(verify_config, deep=True)
    evidence = _recovered_evidence(verify_config)
    # Every commit that was reported to the caller must still be visible. The
    # last observed revision is a *lower bound*: the process may have committed
    # one more before the signal landed. Nothing above is guaranteed.
    last_seen = before["revision"]
    replay = ops._head_on_disk(paths["db"])
    checks = {
        "killed_by_sigkill": finished == -signal.SIGKILL,
        "no_clean_marker": not at_crash["clean_marker"],
        "wal_present_at_crash": at_crash["wal_exists"],
        "recovery_integrity_ok": recovered["ok"],
        "recovered_head_at_least_last_reported": replay is not None and replay >= last_seen,
        "recovered_head_is_bounded": replay is not None and replay <= last_seen + 1,
        "commits_visible": recovered["counts"]["commits"] >= 1,
        "every_reported_commit_present": (evidence["log_last"] is not None
                                          and evidence["log_last"] >= last_seen),
        "log_contiguous_after_recovery": evidence["log_contiguous"],
        "index_matches_documents_after_recovery": evidence["index_matches_documents"],
    }
    return {
        "drill": "sigkill", "ok": all(checks.values()), "checks": checks,
        "exit_signal": finished, "last_reported_revision": last_seen,
        "recovered_head": replay, "at_crash": at_crash, "verification": recovered,
        "recovered_evidence": evidence,
        "note": "a commit whose caller saw a success is never lost; a commit that "
                "was in flight at SIGKILL may or may not be present, and the "
                "recovered head is bounded to last_reported+1",
    }


def torn_commit(config: dict, root: Path) -> dict:
    """SIGKILL in the middle of a write transaction.

    The child opens the real database, starts an IMMEDIATE transaction, writes
    a version row, a commit row, and the head watermark — then is killed before
    COMMIT. On reopen, the head must be unchanged and the partially-written
    document must be invisible. This is the "in-flight is not confirmed" half
    of the durability contract.
    """
    base = _prepare_workspace(root / "torn", config, root / "torn" / "service.conf")
    live = ops.load_config(base)
    paths = ops.config_paths(live)
    Database = ops._seed_from_environment()
    database = Database(str(paths["db"]), timeout=live["STRATALEAF_BUSY_TIMEOUT"])
    try:
        database.catalog.create("events", {"fields": {"worker": "string", "seq": "integer"}})
        database.batch().put("events", "confirmed", {"worker": "a", "seq": 1}).commit()
        committed_head = database.revision
    finally:
        database.close()
    # Now kill a writer mid-transaction. The child does not use the library's
    # commit path, because the point is to force a torn write at the SQL layer.
    child = subprocess.Popen(
        [sys.executable, "-c", _TORN_SCRIPT, str(paths["db"]), str(committed_head + 1)],
        stdout=subprocess.PIPE, text=True)
    try:
        line = child.stdout.readline().strip()
        try:
            ready = json.loads(line)
        except ValueError as exc:
            raise RuntimeError("torn-commit child failed to start: " + line) from exc
        if ready.get("event") != "torn-ready":
            raise RuntimeError("torn-commit child failed to start: " + line)
        child.send_signal(signal.SIGKILL)
        finished = child.wait(timeout=10)
    finally:
        if child.poll() is None:
            child.kill()
    at_crash = {"wal_bytes_before_kill": ready["wal_bytes"],
                "wal_bytes_after_kill": paths["wal"].stat().st_size if paths["wal"].exists() else 0,
                "head_written_in_open_transaction": ready["head_in_txn"],
                "exit_signal": finished}
    recovered = ops.verify(live, deep=True, expect_head=committed_head)
    evidence = _recovered_evidence(live)
    phantom = [item for item in evidence["documents"] if item["key"] == "phantom"]
    checks = {
        "child_was_killed": finished == -signal.SIGKILL,
        "uncommitted_frames_were_durable": at_crash["wal_bytes_before_kill"] > 0,
        "head_unchanged": recovered["head"] == committed_head,
        "phantom_document_absent": not phantom,
        "confirmed_document_present": any(item["key"] == "confirmed"
                                          for item in evidence["documents"]),
        "log_has_no_uncommitted_revision": evidence["log_last"] == committed_head,
        "index_has_no_phantom_row": evidence["index_rows"] == evidence["index_expected_rows"],
        "integrity_ok": recovered["ok"],
    }
    return {"drill": "torn-commit", "ok": all(checks.values()), "checks": checks,
            "committed_head": committed_head, "at_crash": at_crash,
            "recovered_head": recovered["head"], "evidence": evidence,
            "boundary": "a commit is confirmed only when COMMIT returns; a write "
                        "interrupted before that is rolled back by WAL recovery and "
                        "must never appear in reads, the feed, or the index"}


def http_readiness(config: dict, root: Path) -> dict:
    """Prove the endpoint split through the real reference service.

    `/healthz` (liveness) must stay 200 while a long reader blocks the
    checkpoint; `/readyz` (readiness) must return 503. This is the behaviour
    an orchestrator has to implement; asserting only on the library probe
    would leave the container wiring untested.
    """
    import socket
    import urllib.error
    import urllib.request

    base = _prepare_workspace(root / "http", config, root / "http" / "service.conf")
    live = ops.load_config(base)
    paths = ops.config_paths(live)
    port = _free_port()
    environment = dict(os.environ, STRATALEAF_CONF=str(base), STRATALEAF_PORT=str(port))
    environment.setdefault("STRATALEAF_DRILL_ALLOW_PSEUDO", os.environ.get("STRATALEAF_DRILL_ALLOW_PSEUDO", ""))
    log = root / "http" / "server.log"
    handle = open(log, "ab", buffering=0)
    server = subprocess.Popen([sys.executable, str(SERVER)], stdout=handle, stderr=subprocess.STDOUT,
                              env=environment)
    reader = None

    def get(path: str):
        try:
            with urllib.request.urlopen(f"http://127.0.0.1:{port}{path}", timeout=10) as response:
                return response.status, json.loads(response.read())
        except urllib.error.HTTPError as exc:
            return exc.code, json.loads(exc.read())

    try:
        if not _wait_for(lambda: _port_open(port), timeout=20):
            raise RuntimeError("reference service did not start; see " + str(log))
        first = {"healthz": get("/healthz"), "readyz": get("/readyz")}
        for index in range(120):
            request = urllib.request.Request(
                f"http://127.0.0.1:{port}/events",
                data=json.dumps({"key": f"h{index}", "worker": "http", "seq": index}).encode(),
                method="POST")
            with urllib.request.urlopen(request, timeout=10) as response:
                if response.status != 201:
                    raise RuntimeError("write endpoint returned " + str(response.status))
        reader = subprocess.Popen(
            [sys.executable, "-c", _READER_SCRIPT, str(paths["db"]), "30"],
            stdout=subprocess.PIPE, text=True)
        if reader.stdout.readline().strip() != "reader-ready":
            raise RuntimeError("long reader failed to start")
        for index in range(120, 360):
            request = urllib.request.Request(
                f"http://127.0.0.1:{port}/events",
                data=json.dumps({"key": f"h{index}", "worker": "http", "seq": index}).encode(),
                method="POST")
            with urllib.request.urlopen(request, timeout=10) as response:
                if response.status != 201:
                    raise RuntimeError("write endpoint failed while reader held: " + str(response.status))
        blocked = {"healthz": get("/healthz"), "readyz": get("/readyz")}
    finally:
        if reader is not None:
            reader.kill()
            reader.wait()
        server.terminate()
        try:
            server.wait(timeout=15)
        except subprocess.TimeoutExpired:
            server.kill()
            server.wait()
        handle.close()
    server_closed = server.returncode

    handle = open(log, "ab", buffering=0)
    server = subprocess.Popen([sys.executable, str(SERVER)], stdout=handle, stderr=subprocess.STDOUT,
                              env=environment)
    try:
        if not _wait_for(lambda: _port_open(port), timeout=20):
            raise RuntimeError("reference service did not restart")
        after = {"healthz": get("/healthz"), "readyz": get("/readyz")}
    finally:
        server.terminate()
        try:
            server.wait(timeout=15)
        except subprocess.TimeoutExpired:
            server.kill()
            server.wait()
        handle.close()
    recovered = ops.verify(live, deep=True)
    checks = {
        "started_healthy": first["healthz"][0] == 200 and first["readyz"][0] == 200,
        "writes_accepted_while_reader_held": True,
        "liveness_200_while_reader_held": blocked["healthz"][0] == 200,
        "readiness_503_while_reader_held": blocked["readyz"][0] == 503,
        "readiness_reports_degraded": blocked["readyz"][1].get("status") in ("degraded", "not-ready"),
        "service_exited_on_sigterm": server_closed == 0,
        "restart_is_healthy": after["healthz"][0] == 200 and after["readyz"][0] == 200,
        "data_survived_restart": recovered["ok"] and recovered["counts"]["versions"] >= 360,
    }
    return {"drill": "http-readiness", "ok": all(checks.values()), "checks": checks,
            "port": port, "initial": first, "while_reader_held": blocked,
            "after_restart": after, "verification": recovered,
            "boundary": "restarting the container on readiness failure would discard the "
                        "reader; readiness is the signal to stop routing new work, not "
                        "to kill the process"}


def _free_port() -> int:
    import socket
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


def _port_open(port: int) -> bool:
    import socket
    with socket.socket() as sock:
        sock.settimeout(0.2)
        try:
            sock.connect(("127.0.0.1", port))
            return True
        except OSError:
            return False


def long_reader_checkpoint(config: dict, root: Path) -> dict:
    """A long read must make checkpoint lag *without raising*, and readiness
    (not liveness) must catch it.

    WAL mode deliberately lets readers and the writer coexist, so a process
    that is alive and accepting writes can still be draining WAL headroom and
    approaching a full volume. This drill separates the two signals.
    """
    base = _prepare_workspace(root / "reader", config, root / "reader" / "service.conf")
    live = ops.load_config(base)
    paths = ops.config_paths(live)
    Database = ops._seed_from_environment()
    database = Database(str(paths["db"]), timeout=live["STRATALEAF_BUSY_TIMEOUT"])
    reader = None
    try:
        database.catalog.create("segments", {"fields": {"region": "string", "sequence": "integer"}})
        database.batch().put("segments", "seg_00", {"region": "east", "sequence": 0}).commit()
        wal_before = paths["wal"].stat().st_size if paths["wal"].exists() else 0
        reader = subprocess.Popen(
            [sys.executable, "-c", _READER_SCRIPT, str(paths["db"]), "30"],
            stdout=subprocess.PIPE, text=True)
        line = reader.stdout.readline().strip()
        if line != "reader-ready":
            raise RuntimeError("long reader failed to start: " + line)
        for index in range(200):
            database.batch().put("segments", f"seg_{index:03}",
                                 {"region": "west", "sequence": index + 1}).commit()
        wal_after_writes = paths["wal"].stat().st_size
        reports = []
        for _attempt in range(3):
            reports.append({**ops.checkpoint(paths["db"], "PASSIVE", live["STRATALEAF_BUSY_TIMEOUT"]),
                            "wal_bytes": paths["wal"].stat().st_size})
        # The naive signals must all look fine while readiness is blocked.
        naive = {
            "pid_alive": True,
            "db_file_exists": paths["db"].exists(),
            "wal_file_exists": paths["wal"].exists(),
            "checkpoint_raised": False,
            "quick_check": _quick_check(paths["db"]),
        }
        liveness = _probe_status(ops.probe, live, "liveness")
        readiness = _probe_status(ops.probe, live, "readiness")
        while_read = {
            "naive_signals": naive,
            "checkpoint_reports": reports,
            "checkpoint_lagging": any(not item["complete"] for item in reports),
            "wal_bytes_before_writes": wal_before,
            "wal_bytes_after_writes": wal_after_writes,
            "wal_growth_bytes": wal_after_writes - wal_before,
            "liveness_probe": liveness,
            "readiness_probe": readiness,
        }
    finally:
        if reader is not None:
            reader.kill()
            reader.wait()
    # After the reader releases, the same PASSIVE call must make progress.
    released = ops.checkpoint(paths["db"], "PASSIVE", live["STRATALEAF_BUSY_TIMEOUT"])
    after_release = {
        "checkpoint": released,
        "wal_bytes": paths["wal"].stat().st_size if paths["wal"].exists() else 0,
        "readiness_probe": _probe_status(ops.probe, live, "readiness"),
    }
    naive_ok = (naive["quick_check"] == "ok" and naive["db_file_exists"]
                and naive["wal_file_exists"] and not naive["checkpoint_raised"])
    checks = {
        "checkpoint_did_not_raise": True,
        "checkpoint_lagged_while_reader_held": while_read["checkpoint_lagging"],
        "wal_grew_while_blocked": (while_read["checkpoint_reports"][-1]["log_frames"]
                                   > while_read["checkpoint_reports"][0]["checkpointed_frames"]),
        "naive_checks_all_passed": naive_ok,
        "liveness_still_healthy": liveness["status"] == "healthy",
        "readiness_degraded_while_reader_held": readiness["status"] in ("degraded", "not-ready"),
        "checkpoint_completed_after_release": released["complete"],
        "readiness_healthy_after_release": after_release["readiness_probe"]["status"] == "healthy",
    }
    database.close()
    return {"drill": "long-reader-checkpoint", "ok": all(checks.values()),
            "checks": checks, "while_read_locked": while_read,
            "after_release": after_release,
            "boundary": "file exists, pid alive, quick_check ok, and a checkpoint "
                        "call that returns without raising are all true while the "
                        "checkpoint is silently making no progress; only readiness "
                        "distinguishes this from an idle, healthy service"}


def write_conflict(config: dict, root: Path) -> dict:
    """A second writer must get a bounded, explicit busy error — not success."""
    base = _prepare_workspace(root / "conflict", config, root / "conflict" / "service.conf")
    live = ops.load_config(base)
    paths = ops.config_paths(live)
    Database = ops._seed_from_environment()
    database = Database(str(paths["db"]), timeout=0.2)
    holder = None
    try:
        database.catalog.create("segments", {"fields": {"region": "string", "sequence": "integer"}})
        database.batch().put("segments", "seg_00", {"region": "east", "sequence": 0}).commit()
        holder = ops.sqlite3.connect(str(paths["db"]), isolation_level=None)
        holder.execute("BEGIN IMMEDIATE")
        started = time.monotonic()
        try:
            database.batch().put("segments", "seg_00", {"region": "west", "sequence": 1}).commit()
            blocked = None
        except ops.sqlite3.OperationalError as exc:
            blocked = {"type": type(exc).__name__, "message": str(exc),
                       "elapsed_ms": round((time.monotonic() - started) * 1000, 2)}
        holder.execute("ROLLBACK")
        after = database.batch().put("segments", "seg_00", {"region": "west", "sequence": 1}).commit()
        current = database.get("segments", "seg_00")
        checks = {
            "second_writer_blocked": blocked is not None,
            "error_is_busy": blocked is not None and "locked" in blocked["message"],
            "waited_about_busy_timeout": blocked is not None and 120 <= blocked["elapsed_ms"] <= 2000,
            "wrote_after_release": after.count == 1,
            "document_is_new_value": current is not None and current.document["region"] == "west",
        }
        return {"drill": "write-conflict", "ok": all(checks.values()), "checks": checks,
                "blocked": blocked, "after_release": after.__dict__,
                "visible": current.document if current else None,
                "boundary": "SQLite gives one writer per database; callers treat "
                            "OperationalError as retryable and never as a lost commit"}
    finally:
        if holder is not None:
            holder.close()
        database.close()


def space_pressure(config: dict, root: Path) -> dict:
    """Deterministic disk-exhaustion analog using RLIMIT_FSIZE.

    Mount namespaces are unavailable in this environment, so we cap the file
    size for a child process. SQLite surfaces `disk I/O error`; committed data
    must remain readable and the preflight reserve must refuse the next start.
    """
    base = _prepare_workspace(root / "space", config, root / "space" / "service.conf")
    live = ops.load_config(base)
    paths = ops.config_paths(live)
    Database = ops._seed_from_environment()
    database = Database(str(paths["db"]), timeout=1.0)
    try:
        database.catalog.create("segments", {"fields": {"region": "string", "sequence": "integer"}})
        database.batch().put("segments", "keep", {"region": "north", "sequence": 1}).commit()
        committed_head = database.revision
    finally:
        database.close()
    limit = 256 * 1024
    script = _SPACE_SCRIPT
    finished = subprocess.run([sys.executable, "-c", script, str(paths["db"]), str(limit)],
                              capture_output=True, text=True, timeout=120)
    events = []
    for line in finished.stdout.splitlines():
        try:
            events.append(json.loads(line))
        except ValueError:
            events.append({"raw": line})
    failure = next((item for item in events if item.get("event") == "write-failed"), None)
    committed_survived = ops._head_on_disk(paths["db"])
    integrity_ok = _quick_check(paths["db"]) == "ok"
    # Now prove the start gate refuses a volume below its reserve. Simulate by
    # raising the floor above the actual available bytes.
    tight = dict(live)
    tight["STRATALEAF_MIN_FREE_BYTES"] = ops.free_space(paths["data_dir"])["available_bytes"] + 1
    try:
        ops.preflight(tight)
        gate = {"status": "allowed"}
    except ops.GateError as exc:
        gate = {"status": "refused", "reason": str(exc)}
    checks = {
        "write_failed_with_io_error": failure is not None and "disk I/O" in failure["error"],
        "committed_head_survived": committed_survived == committed_head,
        "integrity_ok_after_failure": integrity_ok,
        "start_gate_refuses_low_space": gate["status"] == "refused",
        "no_partial_commit_visible": _visible_keys(paths["db"]) == ["keep"],
    }
    return {"drill": "space-pressure", "ok": all(checks.values()), "checks": checks,
            "limit_bytes": limit, "failure": failure, "committed_head": committed_head,
            "head_on_disk": committed_survived, "gate": gate, "events": events,
            "note": "RLIMIT_FSIZE is the deterministic stand-in for a full volume; "
                    "the same SQLite error path applies to ENOSPC"}


def network_fs_guard(config: dict, root: Path) -> dict:
    """Classify real mounts, and prove the policy rejects network/pseudo FSes.

    Nothing is mounted here; classification of the live volumes is reported as
    fact and synthetic mountinfo lines exercise the rejection path.
    """
    live = ops.load_config(_prepare_workspace(root / "netfs", config, root / "netfs" / "service.conf"))
    paths = ops.config_paths(live)
    real = {}
    for name, path in (("data", paths["data_dir"]), ("state", paths["state_dir"])):
        try:
            real[name] = ops.mount_for(path)
        except ops.GateError as exc:
            real[name] = {"error": str(exc)}
    synthetic = {
        "nfs4": ops.classify_fs("nfs4"),
        "cifs": ops.classify_fs("cifs"),
        "9p": ops.classify_fs("9p"),
        "tmpfs": ops.classify_fs("tmpfs"),
        "overlay": ops.classify_fs("overlay"),
        "ext4": ops.classify_fs("ext4"),
        "xfs": ops.classify_fs("xfs"),
    }
    rejects = {kind: ops.classify_fs(kind)[0] != "persistent-local"
               for kind in ("nfs4", "cifs", "9p", "tmpfs", "overlay")}
    accepts = {kind: ops.classify_fs(kind)[0] == "persistent-local" for kind in ("ext4", "xfs")}
    checks = {
        "network_fs_rejected": all(rejects.values()),
        "local_fs_accepted": all(accepts.values()),
        "data_volume_classified": real["data"].get("fstype") is not None,
        "state_volume_classified": real["state"].get("fstype") is not None,
    }
    return {"drill": "network-fs-guard", "ok": all(checks.values()), "checks": checks,
            "live_mounts": real, "classification": synthetic,
            "boundary": "NFS/CIFS/9p/SMB and FUSE shares are rejected at preflight: "
                        "they cannot provide the POSIX locking and rename/fsync "
                        "semantics SQLite WAL needs, and multi-master writes over "
                        "a shared share are explicitly unsupported"}


def identity_gate(config: dict, root: Path) -> dict:
    """Preflight must reject a wrong uid/gid, root, and a world-writable volume."""
    base = _prepare_workspace(root / "identity", config, root / "identity" / "service.conf")
    live = ops.load_config(base)
    paths = ops.config_paths(live)
    checks: dict[str, bool] = {}
    accepted = ops.preflight(live)
    checks["correct_identity_accepted"] = accepted["ok"]
    try:
        ops.preflight(live, running_uid=0, running_gid=0)
        wrong_uid = "allowed"
    except ops.GateError as exc:
        wrong_uid = str(exc)
    checks["root_refused"] = "uid 0" in wrong_uid
    try:
        ops.preflight(live, running_uid=live["STRATALEAF_UID"] + 1, running_gid=live["STRATALEAF_GID"])
        mismatch = "allowed"
    except ops.GateError as exc:
        mismatch = str(exc)
    checks["uid_mismatch_refused"] = "expected" in mismatch
    world = paths["state_dir"]
    original_mode = os.stat(world).st_mode
    try:
        os.chmod(world, 0o777)
        try:
            ops.preflight(live)
            world_writable = "allowed"
        except ops.GateError as exc:
            world_writable = str(exc)
        checks["world_writable_refused"] = "world-writable" in world_writable
    finally:
        os.chmod(world, original_mode)
    return {"drill": "identity-gate", "ok": all(checks.values()), "checks": checks,
            "running_uid": os.getuid(), "configured_uid": live["STRATALEAF_UID"],
            "uid_mismatch_reason": mismatch, "world_writable_reason": world_writable}


