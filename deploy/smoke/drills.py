def _jsonl(path: Path) -> list[dict]:
    if not path.exists():
        return []
    entries = []
    for line in path.read_text().splitlines():
        try:
            entries.append(json.loads(line))
        except ValueError:
            entries.append({"malformed": line})
    return entries


def _run_child(config_path: Path, seconds: float, batch_interval: float,
               log: Path, env: dict | None = None) -> subprocess.Popen:
    command = [sys.executable, str(OPS), "--config", str(config_path),
               "supervise", "--seconds", str(seconds), "--batch-interval", str(batch_interval)]
    handle = open(log, "ab", buffering=0)
    process = subprocess.Popen(command, stdout=handle, stderr=subprocess.STDOUT, env=env)
    process._log_handle = handle  # keep the file object alive for the drill
    return process


def _wait_for(predicate, timeout: float, interval: float = 0.02) -> bool:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if predicate():
            return True
        time.sleep(interval)
    return False


def _wait_for_commits(running: Path, count: int, timeout: float) -> dict:
    """Wait until the service has published *count* successful commits.

    This makes the drill assert against a non-trivial revision history rather
    than stopping the moment the process comes up.
    """
    seen: dict = {}

    def enough() -> bool:
        try:
            seen.update(json.loads(running.read_text()))
        except (OSError, ValueError):
            return False
        return seen.get("commits", 0) >= count

    if not _wait_for(enough, timeout):
        raise RuntimeError(
            f"service published only {seen.get('commits', 0)} commits in {timeout}s")
    return seen


def _prepare_workspace(root: Path, config: dict, config_path: Path) -> Path:
    if root.exists():
        shutil.rmtree(root)
    data, state = root / "data", root / "state"
    data.mkdir(parents=True)
    state.mkdir(parents=True)
    # Do not inherit the host umask: a volume created 0777 would (correctly)
    # be refused by preflight. The documented volume mode is 0750.
    os.chmod(data, 0o750)
    os.chmod(state, 0o750)
    config_path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# generated by drills.py; absolute paths for this run"]
    for key, value in config.items():
        if key == "STRATALEAF_DATA_DIR":
            value = data
        elif key == "STRATALEAF_STATE_DIR":
            value = state
        lines.append(f"{key}={value}")
    config_path.write_text("\n".join(lines) + "\n")
    return config_path


